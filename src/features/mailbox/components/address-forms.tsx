const ADJECTIVES = ['quick', 'lazy', 'happy', 'brave', 'calm', 'eager', 'fancy', 'gentle', 'jolly', 'kind', 'lucky', 'mighty', 'proud', 'silly', 'sunny', 'witty', 'zesty', 'bold', 'cool', 'swift']
const NOUNS = ['fox', 'panda', 'tiger', 'otter', 'eagle', 'koala', 'whale', 'lion', 'falcon', 'badger', 'cobra', 'dolphin', 'gecko', 'lemur', 'moose', 'raven', 'shark', 'wolf', 'yak', 'zebra']
const pick = <T,>(list: T[]) => list[Math.floor(Math.random() * list.length)]

/** Bind the current mailbox to the logged-in user; a bind failure only shows a toast. Returns whether it was bound. */
async function bindQuietly(bindErrorText: string) {
  try {
    return await bindAddressToUser()
  } catch (error) {
    toast.error(`${bindErrorText}: ${errorMessage(error)}`)
    return false
  }
}

export type AddressLoginResult = {
  /** The mailbox was bound to the logged-in user (false when no user is logged in or binding failed) */
  bound: boolean
}

/** Log in to an existing mailbox by credential (JWT) or by address + password. */
export function AddressLoginForm({ onSuccess }: { onSuccess?: (result: AddressLoginResult) => void }) {
  const t = useT(messages)
  const openSettings = useApp((s) => s.openSettings)
  const userEmail = useApp((s) => s.userSettings.user_email)
  const [method, setMethod] = useState<'credential' | 'password'>(openSettings.enableAddressPassword ? 'password' : 'credential')
  const [credential, setCredential] = useState('')
  const [email, setEmail] = useState('')
  const [password, setPassword] = useState('')
  const [cfToken, setCfToken] = useState('')
  const [loading, setLoading] = useState(false)
  const turnstile = useRef<TurnstileHandle>(null)

  useEffect(() => {
    setMethod(openSettings.enableAddressPassword ? 'password' : 'credential')
  }, [openSettings.enableAddressPassword])

  const submit = async (e: React.FormEvent) => {
    e.preventDefault()
    setLoading(true)
    try {
      if (method === 'password') {
        if (!email || !password) {
          toast.error(t('emailPasswordRequired'))
          return
        }
        const res = await api.post<{ jwt: string }>('/api/address_login', {
          email: email.trim(),
          password: await hashPassword(password),
          cf_token: cfToken,
        })
        await switchAddress(res.jwt)
      } else {
        const value = credential.trim()
        if (!value) {
          toast.error(t('credentialInput'))
          return
        }
        await api.post('/open_api/credential_login', { credential: value, cf_token: cfToken })
        await switchAddress(value)
      }
      const bound = await bindQuietly(t('bindUserAddressError'))
      onSuccess?.({ bound })
    } catch (error) {
      toast.error(errorMessage(error))
      turnstile.current?.refresh()
    } finally {
      setLoading(false)
    }
  }

  const canSwitch = openSettings.enableAddressPassword && !openSettings.addressPasswordLoginOnly
  return (
    <form onSubmit={submit}>
      <FieldGroup>
        {method === 'password' ? (
          <>
            <Field>
              <FieldLabel htmlFor="login-email">{t('email')}</FieldLabel>
              <Input id="login-email" type="email" autoComplete="username" value={email} onChange={(e) => setEmail(e.target.value)} />
            </Field>
            <Field>
              <FieldLabel htmlFor="login-password">{t('password')}</FieldLabel>
              <PasswordInput
                id="login-password"
                autoComplete="current-password"
                value={password}
                onChange={(e) => setPassword(e.target.value)}
              />
            </Field>
          </>
        ) : (
          <Field>
            <FieldLabel htmlFor="login-credential">{t('credential')}</FieldLabel>
            <Textarea
              id="login-credential"
              rows={4}
              className="font-mono text-xs break-all"
              placeholder={t('credentialPlaceholder')}
              value={credential}
              onChange={(e) => setCredential(e.target.value)}
            />
          </Field>
        )}
        {openSettings.enableGlobalTurnstileCheck && <Turnstile ref={turnstile} onToken={setCfToken} />}
        <Button type="submit" disabled={loading} className="w-full">
          {loading ? <Spinner /> : <LogInIcon />}
          {userEmail ? t('loginAndBind') : t('login')}
        </Button>
        {canSwitch && (
          <Button
            type="button"
            variant="link"
            size="sm"
            className="-mt-2 self-center"
            onClick={() => setMethod((m) => (m === 'password' ? 'credential' : 'password'))}
          >
            {method === 'password' ? t('credentialLogin') : t('passwordLogin')}
          </Button>
        )}
      </FieldGroup>
    </form>
  )
}

export type NewAddressResponse = { jwt: string; password?: string; address?: string }
export type NewAddressBody = {
  name: string
  domain: string
  cf_token: string
  enableRandomSubdomain: boolean
  expiresAt?: string | null
  expiresIn?: number | null
}

/**
 * Create a new address. By default posts to `/api/new_address`, switches the current mailbox to it,
 * binds it to the logged-in user, opens the credential dialog, then calls `afterCreated`.
 */
export function CreateAddressForm({
  newAddress,
  onCreated,
  afterCreated,
  showCredential = true,
  enableExpiry = true,
}: {
  newAddress?: (body: NewAddressBody) => Promise<NewAddressResponse>
  /** Replaces the whole default flow (no switch / bind / credential dialog) */
  onCreated?: (res: NewAddressResponse) => void | Promise<void>
  /** Runs after the default flow (e.g. close a dialog) */
  afterCreated?: (res: NewAddressResponse, result: AddressLoginResult) => void | Promise<void>
  /** Open the global credential dialog after creating (default true); turn off when showing your own */
  showCredential?: boolean
  enableExpiry?: boolean
}) {
  const t = useT(messages)
  const openSettings = useApp((s) => s.openSettings)
  const userRole = useApp((s) => s.userSettings.user_role)
  const [name, setName] = useState('')
  const [domain, setDomain] = useState('')
  const [subdomainMode, setSubdomainMode] = useState<'normal' | 'random' | 'custom'>('normal')
  const [customSubdomain, setCustomSubdomain] = useState('')
  const [expiryMode, setExpiryMode] = useState<ExpiryMode>('never')
  const [customExpiry, setCustomExpiry] = useState('')
  const [cfToken, setCfToken] = useState('')
  const [loading, setLoading] = useState(false)
  const turnstile = useRef<TurnstileHandle>(null)

  const addressRegex = useMemo(() => {
    try {
      if (openSettings.addressRegex) return new RegExp(openSettings.addressRegex, 'g')
    } catch (error) {
      console.error('Invalid addressRegex', error)
    }
    return /[^a-z0-9]/g
  }, [openSettings.addressRegex])

  const prefix = userRole ? userRole.prefix || '' : openSettings.prefix

  const domainOptions = useMemo(() => {
    if (userRole) {
      if (!userRole.domains) return openSettings.domains
      return openSettings.domains.filter((d) => userRole.domains!.includes(d.value))
    }
    if (!openSettings.defaultDomains) return openSettings.domains
    return openSettings.domains.filter((d) => openSettings.defaultDomains.includes(d.value))
  }, [openSettings.domains, openSettings.defaultDomains, userRole])

  useEffect(() => {
    if (!domainOptions.some((d) => d.value === domain)) setDomain(domainOptions[0]?.value || '')
  }, [domainOptions, domain])

  const canRandomSubdomain = !!domain && openSettings.randomSubdomainDomains.includes(domain)
  useEffect(() => {
    if (!canRandomSubdomain) setSubdomainMode('normal')
  }, [canRandomSubdomain])

  const expiryEnabled = enableExpiry && openSettings.enableAddressExpiry
  const customName = !openSettings.disableCustomAddressName

  const generateName = () => {
    let generated = `${pick(ADJECTIVES)}${pick(NOUNS)}${Math.floor(Math.random() * 1000)}`.toLowerCase().replace(addressRegex, '')
    if (generated.length > openSettings.maxAddressLen) generated = generated.slice(0, openSettings.maxAddressLen)
    setName(generated)
  }

  const effectiveDomain = subdomainMode === 'custom' ? `${customSubdomain.trim()}.${domain}` : domain

  const submit = async (e: React.FormEvent) => {
    e.preventDefault()
    let expiryPayload: ReturnType<typeof resolveExpiryPayload> = {}
    if (expiryEnabled) {
      const ms = customExpiry ? new Date(customExpiry).getTime() : null
      expiryPayload = resolveExpiryPayload(expiryMode, ms)
      if (!expiryPayload) {
        toast.error(t('invalidExpiryDateTime'))
        return
      }
    }
    setLoading(true)
    try {
      const body: NewAddressBody = {
        name: customName ? name : '',
        domain: effectiveDomain,
        cf_token: cfToken,
        enableRandomSubdomain: subdomainMode === 'random',
        ...expiryPayload,
      }
      const res = newAddress ? await newAddress(body) : await api.post<NewAddressResponse>('/api/new_address', body)
      if (onCreated) {
        await onCreated(res)
      } else {
        await switchAddress(res.jwt)
        useAuth.getState().setAddressPassword(res.password || '')
        const bound = await bindQuietly(t('bindUserAddressError'))
        if (showCredential) useApp.getState().set({ showCredential: true })
        await afterCreated?.(res, { bound })
      }
      setName('')
    } catch (error) {
      toast.error(errorMessage(error))
      turnstile.current?.refresh()
    } finally {
      setLoading(false)
    }
  }

  return (
    <form onSubmit={submit}>
      <FieldGroup>
        <Field>
          <div className="flex items-center justify-between">
            <FieldLabel htmlFor="new-name">{t('email')}</FieldLabel>
            {customName && (
              <Button type="button" variant="ghost" size="xs" onClick={generateName}>
                <DicesIcon />
                {t('generateName')}
              </Button>
            )}
          </div>
          <div className="flex flex-col gap-2 sm:flex-row">
            <InputGroup className="sm:flex-1">
              {prefix && (
                <InputGroupAddon>
                  <InputGroupText>{prefix}</InputGroupText>
                </InputGroupAddon>
              )}
              <InputGroupInput
                id="new-name"
                value={customName ? name : ''}
                disabled={!customName}
                placeholder={customName ? t('namePlaceholder') : t('autoGeneratedName')}
                maxLength={openSettings.maxAddressLen}
                onChange={(e) => setName(e.target.value)}
                autoComplete="off"
              />
              <InputGroupAddon align="inline-end">
                <InputGroupText>@</InputGroupText>
              </InputGroupAddon>
            </InputGroup>
            <Select value={domain} onValueChange={setDomain}>
              <SelectTrigger className="w-full sm:w-auto sm:min-w-44">
                <SelectValue placeholder={t('domain')} />
              </SelectTrigger>
              <SelectContent>
                {domainOptions.map((d) => (
                  <SelectItem key={d.value} value={d.value}>
                    {d.label}
                  </SelectItem>
                ))}
              </SelectContent>
            </Select>
          </div>
          {customName && <FieldDescription>{t('nameTip', { regex: addressRegex.source })}</FieldDescription>}
        </Field>

        {canRandomSubdomain && (
          <Field>
            <FieldLabel>{t('subdomain')}</FieldLabel>
            <RadioGroup value={subdomainMode} onValueChange={(v) => setSubdomainMode(v as typeof subdomainMode)} className="flex flex-wrap gap-4">
              {(['normal', 'random', 'custom'] as const).map((mode) => (
                <div key={mode} className="flex items-center gap-2">
                  <RadioGroupItem value={mode} id={`sub-${mode}`} />
                  <Label htmlFor={`sub-${mode}`} className="font-normal">
                    {t(mode === 'normal' ? 'normalSubdomain' : mode === 'random' ? 'enableRandomSubdomain' : 'enableCustomSubdomain')}
                  </Label>
                </div>
              ))}
            </RadioGroup>
            {subdomainMode === 'random' && <FieldDescription>{t('randomSubdomainTip')}</FieldDescription>}
            {subdomainMode === 'custom' && (
              <InputGroup>
                <InputGroupInput value={customSubdomain} onChange={(e) => setCustomSubdomain(e.target.value)} />
                <InputGroupAddon align="inline-end">
                  <InputGroupText>.{domain}</InputGroupText>
                </InputGroupAddon>
              </InputGroup>
            )}
          </Field>
        )}

        {expiryEnabled && (
          <Field>
            <FieldLabel>{t('expiresAt')}</FieldLabel>
            <div className="flex flex-col gap-2 sm:flex-row">
              <Select value={expiryMode} onValueChange={(v) => setExpiryMode(v as ExpiryMode)}>
                <SelectTrigger className="w-full sm:w-44">
                  <SelectValue />
                </SelectTrigger>
                <SelectContent>
                  {EXPIRY_MODES.map((m) => (
                    <SelectItem key={m} value={m}>
                      {t(EXPIRY_KEYS[m])}
                    </SelectItem>
                  ))}
                </SelectContent>
              </Select>
              {expiryMode === 'custom' && (
                <Input
                  type="datetime-local"
                  step={1}
                  className="sm:flex-1"
                  value={customExpiry}
                  onChange={(e) => setCustomExpiry(e.target.value)}
                />
              )}
            </div>
          </Field>
        )}

        <Turnstile ref={turnstile} onToken={setCfToken} />

        {customName && name && domain && (
          <p className="truncate rounded-lg bg-muted/60 px-3 py-2 text-sm">
            <span className="text-muted-foreground">{t('preview')}: </span>
            <span className="font-mono font-medium">
              {prefix}
              {name}@{subdomainMode === 'random' ? `*.${domain}` : effectiveDomain}
            </span>
          </p>
        )}

        <Button
          type="submit"
          className="w-full"
          disabled={
            loading ||
            !domain ||
            (subdomainMode === 'custom' && !customSubdomain.trim()) ||
            (expiryEnabled && expiryMode === 'custom' && !customExpiry)
          }
        >
          {loading ? <Spinner /> : <MailPlusIcon />}
          {t('getNewEmail')}
        </Button>
      </FieldGroup>
    </form>
  )
}
